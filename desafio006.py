# crie um algoritmo que leia um numero e mostre o seu dobro, triplo e raiz quadrada

numero = int(input('Digite um numero inteiro: '))

dobro = numero * 2 
triplo = numero * 3 
raiz = numero ** (1/2)

print(f'O numero digitado foi {numero} \n seu dobro e o valor {dobro} \n O seu triplo e o valor {triplo} \n sua raiz quadrada e o valor de {raiz}')